def get_dataset(key: str) -> DatasetProfile:
    """Return a dataset profile by stable key."""

    normalized = key.strip().lower()
    for profile in DATASETS:
        if profile.key == normalized:
            return profile
    known = ", ".join(profile.key for profile in DATASETS)
    raise KeyError(f"unknown dataset {key!r}; known keys: {known}")


def registry_as_dicts() -> list[dict[str, object]]:
    """Return JSON-friendly registry entries."""

    return [asdict(profile) for profile in DATASETS]


def render_registry() -> str:
    """Render a compact human-readable registry for the CLI."""

    rows = [
        "key | category | primary role | project location",
        "--- | --- | --- | ---",
    ]
    rows.extend(
        f"{profile.key} | {profile.category} | {profile.primary_role} | {profile.project_location}"
        for profile in DATASETS
    )
    return "\n".join(rows)
