def run_mainline_baseline_comparison(config: MainlineBaselineComparisonConfig) -> dict[str, Any]:
    if config.protocol in {
        "corrected-v2",
        "stabilized-v3",
        "stabilized-v4",
        "stabilized-v4-corrected",
        "core-framework-v1",
        "core-framework-v2",
        "core-framework-v3",
        "core-framework-v4",
        "core-framework-v4-delta-scale",
        "core-framework-v5",
        "core-framework-v6",
        "core-framework-v7",
        "core-framework-v8",
        "core-framework-v9-action-selection",
        "core-framework-v10-safety",
        "core-framework-v11-comm-occluder",
    }:
        from .mainline_corrected import run_corrected_comparison
        return run_corrected_comparison(config)
    """Run the requested seed-42 stage and write auditable comparison artifacts."""

    root = config.resolved_output_dir
    logs = config.resolved_logs_dir
    plots = config.resolved_plots_dir
    if config.stage == "plot-only":
        if not root.is_dir():
            raise FileNotFoundError(f"plot-only reference does not exist: {root}")
        logs.mkdir(parents=True, exist_ok=True)
        plots.mkdir(parents=True, exist_ok=True)
    else:
        if config.stage == "development":
            smoke_root = root.parent / "mainline_baseline_comparison_smoke_seed42"
            smoke_logs = Path("logs/preliminary") / smoke_root.name
            smoke_report_path = smoke_logs / "audit_report.json"
            if not smoke_report_path.is_file():
                raise RuntimeError(
                    "development requires the completed seed=42 smoke audit: "
                    f"{smoke_report_path}"
                )
            smoke_report = _read_json(smoke_report_path)
            if not bool(smoke_report.get("audit_ok", False)):
                raise RuntimeError(
                    "development is blocked because seed=42 smoke audit_ok is false: "
                    f"{smoke_report_path}"
                )
        _prepare_outputs(root, logs, plots, config.force)
        _progress(config, f"training GAT branches at {root}")
        summary = run_communication_constrained_proxy_mappo(_comm_config(config))
        if not summary.get("audit_ok", False):
            raise RuntimeError(f"formal GAT branches failed structural validation: {summary}")
        _progress(config, "training the mlp_flat architecture ablation")
        mlp = _run_mlp_branch(config, root)
        if not mlp["episode_report"].get("ok", False):
            raise RuntimeError(f"mappo_mlp validation failed: {mlp['episode_report']}")
        _progress(config, "replaying the three fixed-control rule baselines")
        for method in FIXED_CONTROL_METHODS:
            _run_rule_method(config, root, method)
        _progress(config, "running fixed-control measurement-choice diagnostic B")
        _run_b_diagnostic(config, root)

    # Keep provenance current for both a freshly generated result and a
    # plot-only regeneration, including the separate proxy mechanism
    # ablation that is intentionally outside the six-method A comparison.
    _write_method_definitions(logs)
    training = _training_rows(root)
    decomposition = _reward_decomposition(root)
    a_rows = _collect_a_rows(root)
    b_rows = _collect_b_rows(root)
    _write_comparison_tables(logs, a_rows, b_rows)
    _write_table(logs / "training_rows.csv", training)
    _write_table(logs / "training_reward_decomposition.csv", decomposition)
    episode_decomposition = _aggregate_reward_decomposition_by_episode(decomposition)
    _write_table(logs / "training_reward_decomposition_episode.csv", episode_decomposition)
    _write_json(logs / "reward_decomposition_closure.json", _check_reward_closure(decomposition))
    structure = _audit_structure(root, logs, a_rows, b_rows, decomposition)
    figures = _plot_figures(root=root, logs=logs, plots=plots / "A", training=training, decomposition=decomposition, a_rows=a_rows, b_rows=b_rows)
    # B is a separate diagnostic surface; reuse the same plotting contract but
    # keep its data and labels out of the A full-system performance figures.
    if b_rows:
        _plot_figures(root=root, logs=logs / "B", plots=plots / "B", training=[], decomposition=[], a_rows=b_rows, b_rows=b_rows)
    audit_ok = bool(
        structure.get("all_learned_schema_ok")
        and structure.get("all_required_methods_present")
        and structure.get("fixed_control_rule_scenario_hashes_same")
        and structure.get("all_reported_metrics_finite")
        and structure.get("reward_decomposition_closure", {}).get("within_tolerance")
    )
    report = {
        "experiment": "mainline_baseline_comparison",
        "stage": config.stage,
        "seed": 42,
        "uav_count": 3,
        "audit_ok": audit_ok,
        "training_counts": {
            "warmup": config.counts[0],
            "train": config.counts[1],
            "validation": config.counts[2],
            "test": config.counts[3],
        },
        "methods": list(METHODS),
        "groups": {
            "A": "full system comparison",
            "B": "fixed-control measurement-choice diagnostic; not a retrained causal estimate",
        },
        "validation_only_for_performance": True,
        "test_data_used_for_fitting_or_selection": False,
        "single_seed_descriptive_only": True,
        "structure": structure,
        "figures": figures,
        "logs": {
            "validation_A": str(logs / "validation_episode_metrics_A.csv"),
            "validation_B": str(logs / "validation_episode_metrics_B.csv"),
            "training": str(logs / "training_rows.csv"),
            "reward_decomposition": str(logs / "training_reward_decomposition.csv"),
            "reward_decomposition_episode": str(logs / "training_reward_decomposition_episode.csv"),
        },
        "conclusion_boundary": "seed=42 describes one training realization; no cross-seed stability or universal superiority claim",
    }
    _write_json(logs / "audit_report.json", report)
    _write_json(root / "comparison_manifest.json", report)
    return {
        "output_dir": str(root),
        "logs_dir": str(logs),
        "plots_dir": str(plots),
        "audit_ok": audit_ok,
        "single_seed_only": True,
        "audit_report": str(logs / "audit_report.json"),
        "figures": figures,
    }


