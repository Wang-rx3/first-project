def _reward_decomposition(root: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for method in LEARNED_METHODS:
        scale = root / "seed_42" / method / "scale_3"
        for episode_root in sorted((scale / "train").glob("episode_*")):
            reward_path = episode_root / "rewards.csv"
            scenario_path = episode_root / "scenario.json"
            if not reward_path.is_file() or not scenario_path.is_file():
                continue
            scenario = _read_json(scenario_path)
            reward_config = scenario.get("reward_config", {})
            weights = dict(reward_config.get("weights", {}))
            uncertainty_weight = float(weights.get("uncertainty", 0.35))
            loss_weight = float(weights.get("loss", 0.20))
            aoi_weight = float(weights.get("aoi", 0.15))
            delay_weight = float(weights.get("delay", 0.15))
            connectivity_weight = float(weights.get("connectivity", 0.15))
            collision_penalty = float(reward_config.get("collision_penalty", 10.0))
            by_time: dict[str, list[dict[str, float]]] = {}
            for raw in _read_csv(reward_path):
                timestamp = str(raw.get("timestamp", ""))
                unc = _finite(raw.get("normalized_uncertainty"), 0.0)
                loss = _finite(raw.get("normalized_packet_loss"), 0.0)
                aoi = _finite(raw.get("normalized_aoi"), 0.0)
                delay = _finite(raw.get("normalized_delay"), 0.0)
                conn = _finite(raw.get("normalized_connectivity"), 0.0)
                collision = _finite(raw.get("collision"), 0.0)
                energy = _finite(raw.get("reward_energy"), 0.0)
                loc = -uncertainty_weight * unc
                communication = -(
                    loss_weight * loss
                    + aoi_weight * aoi
                    + delay_weight * delay
                    - connectivity_weight * conn
                )
                by_time.setdefault(timestamp, []).append(
                    {
                        "total": _finite(raw.get("reward_total"), 0.0),
                        "localization": loc,
                        "communication": communication,
                        "collision": -collision_penalty * collision,
                        "energy": energy,
                    }
                )
            for update, (timestamp, values) in enumerate(sorted(by_time.items()), start=1):
                aggregate = {key: _mean(item[key] for item in values) for key in values[0]}
                aggregate.update(
                    {
                        "method": method,
                        "episode_id": episode_root.name,
                        "update": update,
                        "timestamp": _finite(timestamp, float(update)),
                        "closure_error": aggregate["total"]
                        - sum(aggregate[key] for key in ("localization", "communication", "collision", "energy")),
                    }
                )
                rows.append(aggregate)
    return rows


def _check_reward_closure(rows: Sequence[Mapping[str, Any]], tolerance: float = 1e-6) -> dict[str, Any]:
    errors = np.asarray([abs(_finite(row.get("closure_error"), 0.0)) for row in rows], dtype=float)
    maximum = float(errors.max()) if errors.size else 0.0
    return {"row_count": len(rows), "max_abs_error": maximum, "within_tolerance": bool(maximum <= tolerance)}


def _aggregate_reward_decomposition_by_episode(
    rows: Sequence[Mapping[str, Any]],
) -> list[dict[str, Any]]:
    """Aggregate signed reward terms per training episode.

    ``_reward_decomposition`` intentionally retains one row per executed
    decision window so the closure audit can inspect the original granularity.
    Figures, however, should compare episodes rather than draw thousands of
    overlapping window traces.  This helper therefore exposes both the mean
    per-window and the within-episode cumulative views without changing the
    underlying logged values.
    """

    fields = ("total", "localization", "communication", "collision", "energy")
    grouped: dict[tuple[str, str], list[Mapping[str, Any]]] = {}
    for row in rows:
        key = (str(row.get("method", "")), str(row.get("episode_id", "")))
        grouped.setdefault(key, []).append(row)
    output: list[dict[str, Any]] = []
    for method in sorted({key[0] for key in grouped}):
        episode_ids = sorted(
            {key[1] for key in grouped if key[0] == method},
            key=lambda value: int(value.rsplit("_", 1)[-1]) if value.rsplit("_", 1)[-1].isdigit() else value,
        )
        for episode_index, episode_id in enumerate(episode_ids, start=1):
            selected = grouped[(method, episode_id)]
            record: dict[str, Any] = {
                "base_seed": 42,
                "uav_count": 3,
                "method": method,
                "episode_id": episode_id,
                "training_episode": episode_index,
                "window_count": len(selected),
            }
            for field in fields:
                values = [_finite(row.get(field), 0.0) for row in selected]
                record[f"{field}_mean_per_window"] = _mean(values, 0.0)
                record[f"{field}_cumulative"] = float(sum(values))
            record["closure_error_mean_per_window"] = _mean(
                (row.get("closure_error") for row in selected), 0.0
            )
            record["closure_error_cumulative"] = float(
                sum(_finite(row.get("closure_error"), 0.0) for row in selected)
            )
            output.append(record)
    return output


