def _finite(value: Any, default: float = float("nan")) -> float:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return float(default)
    return number if math.isfinite(number) else float(default)


def _mean(values: Iterable[Any], default: float = float("nan")) -> float:
    array = np.asarray([_finite(value) for value in values], dtype=float)
    array = array[np.isfinite(array)]
    return float(array.mean()) if array.size else float(default)


def _std(values: Iterable[Any], default: float = 0.0) -> float:
    array = np.asarray([_finite(value) for value in values], dtype=float)
    array = array[np.isfinite(array)]
    return float(array.std(ddof=1)) if array.size > 1 else float(default)


def _write_table(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    columns: list[str] = []
    seen: set[str] = set()
    for row in rows:
        for key in row:
            if str(key) not in seen:
                seen.add(str(key))
                columns.append(str(key))
    if not columns:
        columns = ["empty"]
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({column: row.get(column, "") for column in columns})


def _json_hash(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _prepare_outputs(root: Path, logs: Path, plots: Path, force: bool) -> None:
    targets = (root, logs, plots)
    existing = [path for path in targets if path.exists() and any(path.iterdir())]
    if existing and not force:
        raise FileExistsError(
            "mainline comparison output is not empty; use --force only for these new roots: "
            + ", ".join(str(path) for path in existing)
        )
    if force:
        for path in targets:
            if path.exists():
                shutil.rmtree(path)
    for path in targets:
        path.mkdir(parents=True, exist_ok=True)


