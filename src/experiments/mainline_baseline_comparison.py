def _rule_action(
    method: str,
    observations: Mapping[str, Mapping[str, Any]],
    environment: Any,
    *,
    budgets: Mapping[str, int],
    cursors: dict[str, int],
    rng: np.random.Generator,
    proxy_model: Mapping[str, Any] | None,
) -> tuple[dict[str, dict[str, Any]], list[dict[str, Any]]]:
    from .baseline import independent_fixed_actions

    actions = independent_fixed_actions(observations, environment.config.motion, cruise_speed_mps=3.0)
    diagnostics: list[dict[str, Any]] = []
    scales = _proxy_scales(proxy_model) if isinstance(proxy_model, Mapping) else None
    for uav_id in environment.uav_ids:
        candidates = sorted(
            actor_visible_measurement_candidates(observations[uav_id], environment.uav_ids)
        )
        selected = "none"
        score = float("nan")
        if method != "local_only_fixed" and cursors.get(uav_id, 0) < int(budgets.get(uav_id, 0)) and candidates:
            if method == "random_cooperative":
                selected = str(candidates[int(rng.integers(0, len(candidates)))])
            elif method == "budgeted_greedy_ig":
                if scales is not None:
                    rows = _online_candidate_rows(
                        observations[uav_id],
                        environment.uav_ids,
                        scales,
                        float(
                            getattr(
                                environment.config.sensor,
                                "uwb_position_std_m",
                                environment.config.sensor.uwb_los_std_m,
                            )
                        ),
                        float(proxy_model.get("age_variance_coefficient", 1.0)),
                    )
                    valid = [row for row in rows if int(row.get("proxy_valid", 0))]
                    valid.sort(key=lambda row: (-_finite(row.get("expected_information_gain_raw"), -1e30), str(row.get("source_uav_id", ""))))
                    if valid:
                        selected = str(valid[0]["source_uav_id"])
                        score = _finite(valid[0].get("expected_information_gain_raw"))
            if selected != "none":
                cursors[uav_id] = int(cursors.get(uav_id, 0)) + 1
        actions[uav_id]["measurement_uav_id"] = selected
        diagnostics.append(
            {
                "uav_id": uav_id,
                "method": method,
                "selected_measurement_uav_id": selected,
                "candidate_count": len(candidates),
                "budget_before": int(cursors.get(uav_id, 0) - (selected != "none")),
                "budget_after": int(cursors.get(uav_id, 0)),
                "greedy_information_gain_raw": score,
                "actor_visible_only": 1,
                "uses_truth_error": 0,
                "uses_physical_los": 0,
                "uses_future_information": 0,
            }
        )
    return actions, diagnostics


def _append_event_rows(scale_root: Path, split: str, episode_id: str, events: Sequence[Mapping[str, Any]]) -> None:
    existing = scale_root / "diagnostics" / f"{split}_cooperative_updates.jsonl"
    if existing.exists():
        with existing.open(encoding="utf-8") as handle:
            if any(json.loads(line).get("episode_id") == episode_id for line in handle if line.strip()):
                raise FileExistsError(f"cooperative events already recorded for {episode_id}: {existing}")
    existing.parent.mkdir(parents=True, exist_ok=True)
    existing.touch(exist_ok=True)
    for event in events:
        payload = {"episode_id": episode_id, "split": split, **dict(event)}
        for name in ("cooperative_updates.jsonl", f"{split}_cooperative_updates.jsonl"):
            path = scale_root / "diagnostics" / name
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(payload, ensure_ascii=False, default=str) + "\n")


def _run_rule_episode(
    *,
    method: str,
    formal: FormalExperimentConfig,
    scale_root: Path,
    source_episode: Mapping[str, Any],
    budgets: Mapping[str, int],
    proxy_model: Mapping[str, Any] | None,
    episode_index: int,
    episode_total: int,
    baseline_source: Path | None = None,
    opportunity_rates: Mapping[str, float] | None = None,
) -> dict[str, Any]:
    source_root = (baseline_source or _baseline_scale(scale_root.parent.parent.parent)) / "validation" / str(source_episode["episode_id"])
    require_new_episode(scale_root / "validation" / str(source_episode["episode_id"]))
    scenario_payload = _read_json(source_root / "scenario.json")
    scenario_generation = scenario_payload.get("scenario_generation")
    if not isinstance(scenario_generation, Mapping):
        raise ValueError(f"missing scenario_generation in {source_root / 'scenario.json'}")
    seed = int(source_episode.get("seed", 0))
    _seed_everything(seed)
    environment = _make_environment(
        formal,
        seed,
        metric_scales=formal.metric_scales,
        cooperative_ekf_enabled=True,
        measurement_overhead_enabled=True,
        measurement_budget_enabled=True,
        measurement_budget_by_uav=budgets,
    )
    observations, info = environment.reset(seed=seed, scenario_config=dict(scenario_generation))
    episode_id = str(source_episode["episode_id"])
    writer = _EpisodeTraceWriter(
        episode_root=scale_root / "validation" / episode_id,
        episode_id=episode_id,
        scenario_id=str(source_episode.get("scenario_id", episode_id)),
        split="validation",
        seed=seed,
        phase="validation",
        environment=environment,
        normalization_fitted=True,
        diagnostics_path=scale_root / "diagnostics" / "attention_maps.jsonl",
        policy_source=f"rule_{method}",
    )
    cursors = {uav_id: 0 for uav_id in environment.uav_ids}
    rng = np.random.default_rng(int(seed) * 1009 + sum(ord(char) for char in method))
    all_selection_rows: list[dict[str, Any]] = []
    episode_events: list[dict[str, Any]] = []
    started = time.perf_counter()
    _progress_proxy = f"{method} episode {episode_index}/{episode_total}"
    for step in range(formal.max_steps):
        _assert_observation_finite(observations)
        actions, selections = _rule_action(
            method,
            observations,
            environment,
            budgets=budgets,
            cursors=cursors.copy() if opportunity_rates is not None else cursors,
            rng=rng,
            proxy_model=proxy_model,
        )
        if opportunity_rates is not None:
            from ..simulation.random_streams import indexed_rng
            for uav_id in environment.uav_ids:
                opportunity = indexed_rng(seed, step, "rule_measurement_opportunity", uav_id).random() < float(opportunity_rates[uav_id])
                if not opportunity or cursors[uav_id] >= int(budgets[uav_id]):
                    actions[uav_id]["measurement_uav_id"] = "none"
                for selection in selections:
                    if selection["uav_id"] == uav_id:
                        selection.update(opportunity=int(opportunity), selected_measurement_uav_id=actions[uav_id]["measurement_uav_id"],
                                         budget_before=cursors[uav_id])
        _assert_action_feasible(environment, actions)
        update_counts_before = accepted_counts(environment)
        next_observations, rewards, terminated, truncated, next_info = environment.step(actions)
        if opportunity_rates is not None:
            cursors = dict(environment.measurement_budget_used)
            for selection in selections:
                selection["budget_after"] = cursors[selection["uav_id"]]
                if not np.isfinite(selection["greedy_information_gain_raw"]):
                    selection["greedy_information_gain_raw"] = "NA"
        timestamp = (step + 1) * environment.config.motion.dt_s
        for selection in selections:
            all_selection_rows.append(
                {"episode_id": episode_id, "step": step, "timestamp": timestamp, **selection}
            )
        new_events = collect_window_events(environment, update_counts_before, run_root=scale_root,
                                          episode_id=episode_id, split="validation", step=step)
        for event in new_events:
            event_row = {"step": step, "timestamp": timestamp, "treatment": method, **dict(event)}
            episode_events.append(event_row)
        writer.record_step(
            step=step,
            observations_before=observations,
            observations_after=next_observations,
            actions=actions,
            rewards=rewards,
            info=next_info,
            graph_traces=None,
            policy_source=f"rule_{method}",
            action_start=step * environment.config.motion.dt_s,
            timestamp=timestamp,
            terminated=bool(terminated),
            truncated=bool(truncated),
        )
        observations, info = next_observations, next_info
        if terminated or truncated:
            break
    summary = writer.finalize()
    summary.update(
        seed=seed,
        mean_reward=summary.get("mean_reward", 0.0),
        update=None,
        source_episode_id=episode_id,
        source_scenario_sha256=_sha256(source_root / "scenario.json"),
    )
    _append_event_rows(scale_root, "validation", episode_id, episode_events)
    metrics = _episode_metrics(scale_root / "validation" / episode_id, summary)
    if opportunity_rates is not None and not metrics["accepted_update_count"]:
        for field in ("beneficial_fraction", "neutral_fraction", "harmful_fraction"):
            metrics[field] = "NA"
    metrics.update(
        base_seed=42,
        method=method,
        policy_source=f"rule_{method}",
        rule_selection_rows=len(all_selection_rows),
        budget_total=int(sum(int(value) for value in budgets.values())),
        budget_used=int(sum(cursors.values())),
        budget_excess=0,
        scenario_hash=_sha256(source_root / "scenario.json"),
    )
    selection_path = scale_root / "diagnostics" / "rule_selection.jsonl"
    selection_path.parent.mkdir(parents=True, exist_ok=True)
    with selection_path.open("a", encoding="utf-8") as handle:
        for row in all_selection_rows:
            handle.write(json.dumps(row, ensure_ascii=False, default=str) + "\n")
    return metrics


def _run_rule_method(
    config: MainlineBaselineComparisonConfig,
    root: Path,
    method: str,
    *,
    baseline_source: Path | None = None,
    rule_proxy_model: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    baseline = baseline_source or _baseline_scale(root)
    budgets = _fit_measurement_budgets(baseline, uav_count=3)
    # The baseline branch deliberately has no proxy features and therefore
    # does not emit an execution-proxy calibration file.  The shared proxy
    # used by the greedy rule is fitted from baseline/train, then persisted by
    # the communication-constrained branch.  Resolve it there rather than
    # silently turning the greedy rule into an all-none policy.
    proxy_path = baseline / "calibration" / "measurement_proxy_model.json"
    if not proxy_path.is_file():
        proxy_path = (
            root
            / "seed_42"
            / COMMUNICATION_BRANCH
            / "scale_3"
            / "calibration"
            / "measurement_proxy_model.json"
        )
    proxy_model = (
        dict(rule_proxy_model)
        if isinstance(rule_proxy_model, Mapping)
        else (_read_json(proxy_path) if proxy_path.is_file() else None)
    )
    if method == "budgeted_greedy_ig" and not isinstance(proxy_model, Mapping):
        raise RuntimeError(
            "budgeted_greedy_ig requires the baseline-train execution proxy; refusing an all-none fallback"
        )
    scale_root = root / "seed_42" / "rules" / method
    if scale_root.exists() and any(scale_root.iterdir()):
        raise FileExistsError(f"rule result already exists; use a fresh directory: {scale_root}")
    formal = _formal_from_scale(
        baseline,
        scale_root,
        progress=config.progress,
        budget_enabled=True,
        budgets=budgets,
    )
    formal = replace(
        formal,
        mappo_variant="baseline_mappo",
        encoder_type="gat",
        measurement_budget_enabled=True,
        measurement_budget_by_uav=dict(budgets),
        measurement_quality_logit_penalty=0.0,
        command_line=f"run-mainline-baseline-comparison --rule-method {method}",
    )
    if config.protocol in {
        "core-framework-v1",
        "core-framework-v2",
        "core-framework-v3",
        "core-framework-v4",
        "core-framework-v4-delta-scale",
        "core-framework-v5",
        "core-framework-v6",
        "core-framework-v7",
        "core-framework-v8",
        "core-framework-v9-action-selection",
        "core-framework-v10-safety",
        "core-framework-v11-comm-occluder",
    }:
        # The current paper protocol uses the nominal VO covariance for every
        # method.  Historical archives may contain a calibration file, but
        # merely finding that file must not silently change the active
        # comparison's observation model.
        formal = replace(
            formal,
            visual_odometry_quality_calibration_enabled=False,
            visual_odometry_quality_model=None,
        )
    (scale_root / "diagnostics").mkdir(parents=True, exist_ok=True)
    _copy_calibration_files(scale_root, formal)
    episodes = _load_scenario_episodes(baseline, "validation")
    opportunity_rates = None
    if config.protocol in {
        "corrected-v2",
        "stabilized-v3",
        "stabilized-v4",
        "stabilized-v4-corrected",
        "core-framework-v1",
        "core-framework-v2",
        "core-framework-v3",
        "core-framework-v4",
        "core-framework-v4-delta-scale",
        "core-framework-v5",
        "core-framework-v6",
        "core-framework-v7",
        "core-framework-v8",
        "core-framework-v9-action-selection",
        "core-framework-v10-safety",
        "core-framework-v11-comm-occluder",
    }:
        from .measurement_rate_controlled_mappo import _fit_measurement_rate_targets
        opportunity_rates, _ = _fit_measurement_rate_targets(baseline, uav_count=3, base_seed=42)
    rows = [
        _run_rule_episode(
            method=method,
            formal=formal,
            scale_root=scale_root,
            source_episode=episode,
            budgets=budgets,
            proxy_model=proxy_model,
            episode_index=index + 1,
            episode_total=len(episodes),
            baseline_source=baseline,
            opportunity_rates=opportunity_rates,
        )
        for index, episode in enumerate(episodes)
    ]
    # Keep the standard schema while retaining comparison-only provenance
    # fields (method and scenario hash) for the read-only audit layer.
    _write_table(scale_root / "diagnostics" / "validation_episode_metrics.csv", rows)
    manifest = {
        "dataset_id": f"mainline_baseline_comparison_{method}",
        "schema_version": EPISODE_SCHEMA_VERSION,
        "uav_count": 3,
        "method": method,
        "method_definition": BRANCH_LABELS[method],
        "policy_source": f"rule_{method}",
        "train_episodes": 0,
        "validation_episodes": len(rows),
        "test_episodes": 0,
        "measurement_budget": dict(budgets),
        "scenario_source": str(baseline),
        "scenario_hashes": [str(row["scenario_hash"]) for row in rows],
        "test_data_used_for_selection": False,
        "actor_truth_free": True,
        "episodes": rows,
    }
    _write_json(scale_root / "manifest.json", manifest)
    _write_json(
        scale_root / "checks" / "rule_method_checks.json",
        {
            "method": method,
            "trainer_update_called": False,
            "cooperative_measurement_disabled": method == "local_only_fixed",
            "background_communication_retained": True,
            "budget_excess": 0,
            "payload_bytes": 512,
            "truth_or_future_inputs_used": False,
        },
    )
    return {"method": method, "validation_episodes": len(rows), "scale_root": str(scale_root)}


def _checkpoint_trainer(
    scale_root: Path,
    formal: FormalExperimentConfig,
    environment: Any,
) -> MAPPOTrainer:
    import torch

    checkpoint = scale_root / "checkpoints" / "final.pt"
    payload = torch.load(checkpoint, map_location="cpu", weights_only=False)
    if not isinstance(payload, Mapping):
        raise ValueError(f"invalid checkpoint {checkpoint}")
    raw_config = dict(payload.get("trainer_config", {}))
    allowed = {field.name for field in fields(MAPPOConfig)}
    trainer_config = {key: value for key, value in raw_config.items() if key in allowed}
    use_quality = bool(trainer_config.get("use_measurement_quality_features", False))
    use_proxy = bool(trainer_config.get("use_measurement_proxy_features", False))
    quality_path = scale_root / "calibration" / "measurement_quality_model.json"
    proxy_path = scale_root / "calibration" / "measurement_proxy_model.json"
    quality_model = _read_json(quality_path) if use_quality and quality_path.is_file() else None
    proxy_model = _read_json(proxy_path) if use_proxy and proxy_path.is_file() else None
    trainer = MAPPOTrainer.from_environment(
        environment,
        seed=42,
        normalizer=ObservationNormalizer.from_state_dict(payload["normalization_stats"]),
        central_normalizer=FeatureNormalizer.from_state_dict(payload["central_normalization_stats"]),
        measurement_quality_model=quality_model,
        measurement_proxy_model=proxy_model,
        **trainer_config,
    )
    trainer.policy.load_state_dict(payload["policy_state_dict"], strict=True)
    trainer.load_measurement_rate_dual_state_dict(payload.get("measurement_rate_dual_state"))
    trainer.load_measurement_communication_dual_state_dict(payload.get("measurement_communication_dual_state"))
    trainer.policy.eval()
    return trainer


