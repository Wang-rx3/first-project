def _audit_structure(root: Path, logs: Path, a_rows: Sequence[Mapping[str, Any]], b_rows: Sequence[Mapping[str, Any]], decomposition: Sequence[Mapping[str, Any]]) -> dict[str, Any]:
    learned_reports: dict[str, Any] = {}
    for method in (BASELINE_BRANCH, PROXY_BRANCH, COMMUNICATION_BRANCH, "mappo_mlp"):
        scale = root / "seed_42" / method / "scale_3"
        learned_reports[method] = validate_episode_benchmark(scale) if scale.is_dir() else {"ok": False, "missing": str(scale)}
    rule_reports: dict[str, Any] = {}
    for method in FIXED_CONTROL_METHODS:
        scale = root / "seed_42" / "rules" / method
        rule_reports[method] = {
            "ok": scale.is_dir() and (scale / "manifest.json").is_file() and len([row for row in a_rows if row.get("method") == method]) > 0,
            "schema_version": EPISODE_SCHEMA_VERSION,
        }
    all_finite = True
    finite_fields = (
        "position_rmse_norm_m", "position_p95_norm_m", "mean_reward", "j_com",
        "measurement_count", "packet_loss", "delay_s", "aoi_s", "energy_proxy",
        "accepted_updates_per_window", "beneficial_per_window", "harmful_per_window",
    )
    for row in list(a_rows) + list(b_rows):
        all_finite = all_finite and all(math.isfinite(_finite(row.get(field), float("nan"))) for field in finite_fields)
    # A scenario pool contains one hash per episode, so requiring all rule
    # episodes to share a single hash would be incorrect.  Compare the
    # episode-id -> canonical source-hash mapping across rule methods instead.
    rule_maps: list[dict[str, str]] = []
    for method in FIXED_CONTROL_METHODS:
        rule_maps.append(
            {
                str(row.get("episode_id")): str(row.get("scenario_hash", ""))
                for row in a_rows
                if row.get("method") == method
            }
        )
    scenario_hash_ok = bool(rule_maps) and all(mapping == rule_maps[0] for mapping in rule_maps[1:])
    closure = _check_reward_closure(decomposition)
    return {
        "schema_version": EPISODE_SCHEMA_VERSION,
        "seed": 42,
        "uav_count": 3,
        "groups": {"A_full_system": True, "B_fixed_control_measurement_choice_diagnostic": bool(b_rows)},
        "learned_reports": learned_reports,
        "rule_reports": rule_reports,
        "all_learned_schema_ok": all(bool(report.get("ok", False)) for report in learned_reports.values()),
        "all_required_methods_present": all(method in {str(row.get("method")) for row in a_rows} for method in METHODS),
        "validation_episode_count_A_by_method": {method: sum(row.get("method") == method for row in a_rows) for method in METHODS},
        "validation_episode_count_B_by_method": {method: sum(row.get("method") == method for row in b_rows) for method in LEARNED_METHODS},
        "fixed_control_rule_scenario_hashes_same": scenario_hash_ok,
        "all_reported_metrics_finite": all_finite,
        "reward_decomposition_closure": closure,
        "test_data_used_for_fitting_or_selection": False,
        "trainer_update_called_by_rule_methods": False,
        "mappo_loss_not_claimed_as_performance_metric": True,
        "cross_seed_stability_evaluated": False,
    }


